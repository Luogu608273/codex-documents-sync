write('S17','B_lis','B. 最长上升子序列','U2295',r'''
## 题意与范围

给定 1..n 的排列 p。对每个 i，删除所有大于 i 的数，输出剩余序列的严格最长上升子序列长度。n≤10^6。lis.in / lis.out，2 秒，512 MiB。

## 状态与关键性质

设 d[j] 为整个排列中，以位置 j 结尾的最长上升子序列长度。

以值 v 结尾的上升子序列，所有前面的数都小于 v。因此，当阈值 i≥v 时，这些数都不会被删除；计算 d[pos[v]] 不会使用被阈值 i 删除的数。

所以答案为

\[
ans_i=\max_{v\le i}d[pos[v]].
\]

证明：过滤序列的任何上升子序列均以某个 v≤i 结尾，长度不超过该 d；反之，取得该 d 的整条上升子序列值都≤v≤i，仍然保留。两侧相互包含。

## 算法

从左到右计算 LIS。维护 t[len]：已扫描部分中，长度为 len 的上升子序列的最小末尾值。对当前值 x，在 t 中找到第一个≥x 的位置 k，将 t[k] 改为 x，并记 f[x]=k。

严格上升要求前驱末尾<x，因此使用 lower_bound，不能使用 upper_bound。t 的下标 k 就是当前元素结尾的 d：长度 k-1 可以延长，而长度≥k 的旧末尾不小于 x，无法延长成更长序列。

最后按值递增进行 f[i]=max(f[i],f[i-1])，输出 f[i]。

时间 O(n log n)，空间 O(n)，数组约 8 MB。单调递增、单调递减排列分别得到 1,2,..,n 和全 1。

## 部分分

`partial.cpp` 使用

\[
d_i=1+\max_{j<i,p_j<p_i}d_j
\]

直接枚举前驱，再做按值的前缀最大值。O(n²) 时间、O(n) 空间，适用于 n≤5000，即测试点 1～8，按题面条件覆盖 40 分，未在线评测。
''')

write('S17','C_wolf','C. 狼人杀','U2296',r'''
## 题意与范围

n 个人排成一列，狼人不能相邻。村民必须说真话，狼人说什么均可。第 i 人给出方向 d_i 和数 b_i，声称自己左边或右边有恰好 b_i 个狼人。计数合法身份方案，模 998244353。多测，n≥2，Σn≤5×10^5。wolf.in / wolf.out，3 秒，512 MiB。

## 固定狼人总数 q

对于一个**被选为村民**的位置 i，它左侧的狼人数量必须为

\[
t_i(q)=\begin{cases}b_i,&d_i=L,\\q-b_i,&d_i=R.\end{cases}
\]

狼人不能相邻，因此村民的第一个位置只能是 1 或 2；相邻两个村民的位置差只能是 1 或 2；最后一个村民的位置只能是 n 或 n-1。n≥2 保证至少存在一个村民。

定义 f_i：固定 q，已经选出一条以位置 i 为最后一个村民的前缀，之前每个村民的 t 值均与实际左侧狼数一致的方案数。尚未放置的后缀不在状态中。

首个村民在 1 时，左边没有狼人；首个村民在 2 时，位置 1 是狼人。因此

\[
f_1=[t_1=0],\qquad
f_2=[t_2=1]+[t_2=t_1]f_1.
\]

对 i≥3，前一个村民只能在 i-1 或 i-2。两人相邻时中间没有狼人；相隔一个位置时中间恰有一狼。因此

\[
f_i=[t_i=t_{i-1}]f_{i-1}+[t_i=t_{i-2}+1]f_{i-2}.
\]

终点在 n 时右边没有狼人，需要 t_n=q；终点在 n-1 时位置 n 是狼人，需要 t_{n-1}=q-1。固定 q 的答案为

\[
[t_n=q]f_n+[t_{n-1}=q-1]f_{n-1}.
\]

从首项开始，转移每次恰好增加实际间隔中的狼数，因此沿路径的每个 t_i 都自动等于实际左侧狼数，即使公式 t_i 本身可以为负，也不会产生从合法起点到达的错误方案。终点约束保证总狼数正好是 q。

每种合法身份分配唯一对应村民位置路径，并且对应唯一 q，因此枚举 0≤q≤⌈n/2⌉ 求和，不重不漏。

## 从平方优化到 O(n log n)

记两个转移系数为 c_i=[t_i=t_{i-1}]、e_i=[t_i=t_{i-2}+1]，写成矩阵

\[
M_i=\begin{pmatrix}c_i&e_i\\1&0\end{pmatrix},\qquad
\binom{f_n}{f_{n-1}}=M_nM_{n-1}\cdots M_3\binom{f_2}{f_1}.
\]

关键是每个系数在 q 变化时，只会是以下两类之一：

1. 两端发言方向相同：两端 t 的 q 系数相同，等式与 q 无关，恒为 0 或恒为 1。
2. 两端方向不同：q 的系数差为±1，等式最多在一个整数 q=q₀ 成立。

实现中统一将 t_i 写成 α_iq+β_i，其中 L 对应 (0,b_i)，R 对应 (1,-b_i)。对于前驱 j=i-1 或 i-2，要求

\[
(\alpha_i-\alpha_j)q+(\beta_i-\beta_j)=i-j-1.
\]

同方向直接计算常量；异方向求出唯一 q₀，只在 q₀ 开启、q₀+1 关闭。全部系数合计 O(n) 个，每个最多两次修改。

用线段树维护 M_n...M_3。合并时必须为“右区间矩阵 × 左区间矩阵”，因为后面位置的转移左乘。按 q 递增处理事件、单点更新，再用根矩阵与种子计算答案。n=2 时没有矩阵，直接使用 f_2、f_1。

总时间 O(Σn log n)，空间 O(n)。矩阵乘法的每项是两个模数内数乘积的和，小于 2(P-1)²<2×10^18，long long 足够。

## 部分分

`partial.cpp` 固定 q 后直接线性算 f，不使用线段树。每组 O(n²) 时间，O(n) 空间，面向 n≤5000 的测试点 1～8、13～16，按题面编号覆盖 60 分。总开销为 O(Σn²)，不能简写成 O((Σn)²) 的实际执行次数；测试点 13～16 最坏 Σn²≤5×10^8，需结合时限看常数，验证记录单列了实测。本程序不利用“所有方向相同”的额外性质。
''')

