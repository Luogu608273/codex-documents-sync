def P(s,style='p'):
    return Paragraph(escape(s).replace('\n','<br/>'),styles[style])
def eq(s):return P(s,'eq')
def H(s):return P(s,'h')
def page(title,blocks,subtitle=None):
    a=[P(title,'title')]
    if subtitle:a.append(P(subtitle,'sub'))
    for typ,s in blocks:
        a.append(H(s) if typ=='h' else eq(s) if typ=='e' else P(s,'small' if typ=='s' else 'p'))
    return a
